/**
 * Expense Request Collection
 * --------------------------
 * Purpose : Weekly expense requests (Mon–Sat cycle)
 * Used by : APP (request) / ADMIN (approval) / ERP (export)
 *
 * Contains:
 * - Employee identity (man number, name, tag)
 * - Date range (from date → Saturday)
 * - Cycle calculation (days, adjusted days, payable days)
 * - Amounts (per day value, withdrawal charges, total)
 * - Remarks (routes worked in the range, from route sessions)
 */

import { Prop, Schema, SchemaFactory } from '@nestjs/mongoose';
import { HydratedDocument } from 'mongoose';
import { AutoGenerated } from 'src/core/decorators/auto-generated.decorator';
import { ExpenseOption, ExpenseStatus } from 'src/shared/enums/expense.enums';

export type ExpenseDocument = HydratedDocument<Expense>;

@Schema({ timestamps: true, collection: 'expenses' })
export class Expense {
  /* ======================================================
   * IDENTITY
   * ====================================================== */

  @AutoGenerated()
  @Prop({ required: true, unique: true, type: String })
  expenseId!: string;

  // Employee ID (login user)
  @Prop({ required: true, type: String, index: true })
  userId!: string;

  // ERP: Man Number
  @Prop({ type: String, index: true })
  manNumber?: string;

  // ERP: Employee Name
  @Prop({ type: String })
  employeeName!: string;

  // Name of the Per Day Value applied (legacy values: UPC / LOCAL)
  @Prop({ type: String, required: true })
  expenseTag!: string;

  // ExpenseRate.rateId applied
  @Prop({ type: String })
  expenseRateId?: string;

  @Prop({ type: String, enum: ExpenseOption, required: true })
  expenseOption!: ExpenseOption;

  /* ======================================================
   * DATE RANGE
   * ====================================================== */

  // ERP: Requested Date (timestamp the request was hit)
  @Prop({ required: true, type: Date })
  requestedDate!: Date;

  // Monday of the request week (one request per employee per week)
  @Prop({ required: true, type: Date, index: true })
  weekStart!: Date;

  // ERP: From Date
  @Prop({ required: true, type: Date })
  fromDate!: Date;

  // ERP: To Date (always Saturday)
  @Prop({ required: true, type: Date })
  toDate!: Date;

  /* ======================================================
   * CYCLE CALCULATION
   * ====================================================== */

  // ERP: No of days (calendar days From → To, inclusive)
  @Prop({ required: true, type: Number, min: 0 })
  noOfDays!: number;

  // ERP: To be adjusted days (absent days from previous cycle)
  @Prop({ required: true, type: Number, min: 0, default: 0 })
  toBeAdjustedDays!: number;

  // Absent dates of previous cycle (audit trail for adjustment)
  @Prop({ type: [Date], default: [] })
  adjustedDates!: Date[];

  // Previous cycle reference used for adjustment
  @Prop({ type: String })
  previousExpenseId?: string;

  // ERP: Payable days
  @Prop({ required: true, type: Number, min: 0 })
  payableDays!: number;

  /* ======================================================
   * AMOUNTS
   * ====================================================== */

  // ERP: Per Day Value
  @Prop({ required: true, type: Number, min: 0 })
  perDayValue!: number;

  // Slab percentage applied to the base amount (audit trail)
  @Prop({ type: Number, min: 0, max: 100, default: 0 })
  withdrawalChargePercent!: number;

  // ERP: Withdrawal Charges = base amount × withdrawalChargePercent / 100
  @Prop({ required: true, type: Number, min: 0, default: 0 })
  withdrawalCharges!: number;

  // ERP: Total Amount
  @Prop({ required: true, type: Number, min: 0 })
  totalAmount!: number;

  /* ======================================================
   * REMARKS
   * ====================================================== */

  @Prop({ type: [String], default: [] })
  routeIds!: string[];

  // ERP: Remarks (concatenated route names)
  @Prop({ type: String, default: '' })
  remarks!: string;

  /* ======================================================
   * STATUS
   * ====================================================== */

  @Prop({
    type: String,
    enum: ExpenseStatus,
    default: ExpenseStatus.PENDING,
    index: true,
  })
  status!: ExpenseStatus;

  @Prop({ type: String })
  actionBy?: string;

  @Prop({ type: Date })
  actionAt?: Date;

  @Prop({ type: String })
  actionRemarks?: string;

  @Prop({ type: Date })
  erpSyncedAt?: Date;
}

export const ExpenseSchema = SchemaFactory.createForClass(Expense);

ExpenseSchema.index({ userId: 1, weekStart: -1 });
